@pytest.mark.parametrize(
    "entry",
    ["example.com", ".example.com", "10.1.2.3", ".githubcopilot.com", "a-b.c_d.org"],
)
@pytest.mark.parametrize(
    "host",
    ["example.com", "www.example.com", "badexample.com", "example.com.evil", "10.1.2.3",
     "10.1.2.34", "10x1x2x3", "api.githubcopilot.com", "githubcopilot.com", "a-b.c_d.org"],
)  # fmt: skip
def test_filter_regex_agrees_with_host_allowed(entry: str, host: str) -> None:
    # Tinyproxy uses POSIX ERE, case-insensitively; these patterns mean the same in Python.
    matched = re.search(filter_regex(entry), host, re.IGNORECASE) is not None
    assert matched == host_allowed([entry], host)


