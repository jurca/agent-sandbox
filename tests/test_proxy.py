def test_proxy_dockerfile_uses_renamed_binary() -> None:
    text = proxy.proxy_dockerfile("mirror/alpine:3")
    assert text.startswith("FROM mirror/alpine:3\n")
    assert f"/usr/local/bin/{proxy.PROXY_BINARY}" in text
    assert f"{proxy.PROXY_BINARY} -d -c" in proxy.SUPERVISOR_SH
    assert f"USER {proxy.PROXY_UID}:{proxy.PROXY_UID}" in text
    assert f"-o {proxy.PROXY_UID}" in text and proxy.PROXY_DIR in text


