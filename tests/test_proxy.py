# --- Upstream rules ---------------------------------------------------------------------
# Tinyproxy tries domain rules last-defined-first and uses the plain upstream as the default,
# so a later rule overrides an earlier one for the hosts it matches.


def route(lines: list[str], host: str) -> str:
    """Which upstream tinyproxy would use for `host` given the generated lines."""
    default = "direct"
    chosen = None
    for line in lines:
        match = re.fullmatch(r'Upstream (.+?)(?: "([^"]+)")?', line)
        assert match, line
        target, spec = match.groups()
        target = "direct" if target == "none" else target
        if spec is None:
            default = target
        elif _spec_matches(spec, host):
            chosen = target
    return chosen or default


def _spec_matches(spec: str, host: str) -> bool:
    if proxy._network(spec) is not None:
        try:
            return overlaps(host, spec) and proxy._network(host) is not None
        except ValueError:
            return False
    if spec.startswith("."):
        return host.endswith(spec)
    return host == spec


CORP = ProxyEnv(
    upstream=Upstream("http", "proxy.dev.example", 3128),
    no_proxy=(".corp.example", "10.0.0.0/8"),
)
NULL = "http 0.0.0.0:0"
UP = "http proxy.dev.example:3128"


def test_upstream_lines_without_host_proxy() -> None:
    assert upstream_lines(ProxyEnv()) == []


def test_upstream_lines_base_tier() -> None:
    lines = upstream_lines(CORP)
    assert lines == [
        f"Upstream {UP}",
        'Upstream none ".corp.example"',
        'Upstream none "corp.example"',
        'Upstream none "10.0.0.0/8"',
    ]
    assert route(lines, "api.anthropic.com") == UP
    assert route(lines, "git.corp.example") == "direct"
    assert route(lines, "corp.example") == "direct"
    assert route(lines, "10.1.2.3") == "direct"


def test_upstream_lines_direct_all() -> None:
    env = ProxyEnv(upstream=CORP.upstream, no_proxy=(".a.com",), direct_all=True)
    lines = upstream_lines(env)
    assert not any(line.startswith(f"Upstream {UP}") for line in lines)
    assert route(lines, "example.com") == "direct"


def test_upstream_lines_allow_all_null_routes_internal() -> None:
    lines = upstream_lines(CORP, allow_all=True, allowlist=["api.anthropic.com"])
    assert route(lines, "example.com") == UP
    assert route(lines, "api.anthropic.com") == UP
    for host in ("git.corp.example", "corp.example", "10.1.2.3", "192.168.0.1", "127.0.0.1", "localhost",
                 "x.localhost", "169.254.169.254", "100.64.0.1", "172.16.5.5"):  # fmt: skip
        assert route(lines, host) == NULL, host


def test_upstream_lines_allow_all_puts_back_only_the_overlap() -> None:
    lines = upstream_lines(
        CORP,
        allow_all=True,
        allowlist=[".example.com", "git.corp.example", "10.5.5.5", ".corp.example.com"],
    )
    assert route(lines, "git.corp.example") == "direct"
    assert route(lines, "10.5.5.5") == "direct"
    assert route(lines, "other.corp.example") == NULL
    assert route(lines, "10.5.5.6") == NULL
    assert route(lines, "www.example.com") == UP


def test_upstream_lines_allow_all_internal_suffix_inside_allowlisted_domain() -> None:
    env = ProxyEnv(upstream=CORP.upstream, no_proxy=(".int.example.com",))
    lines = upstream_lines(env, allow_all=True, allowlist=[".example.com"])
    # The allowlist names example.com and all subdomains, so the internal part is reachable
    # (directly, as NO_PROXY says), while the rest of example.com keeps using the upstream.
    assert route(lines, "app.int.example.com") == "direct"
    assert route(lines, "www.example.com") == UP
    assert route(lines, "example.com") == UP


def test_upstream_lines_allow_all_private_ip_without_no_proxy_uses_upstream() -> None:
    env = ProxyEnv(upstream=CORP.upstream)
    lines = upstream_lines(env, allow_all=True, allowlist=["192.168.7.7"])
    assert route(lines, "192.168.7.7") == UP
    assert route(lines, "192.168.7.8") == NULL


def test_upstream_lines_allow_all_without_host_proxy() -> None:
    lines = upstream_lines(ProxyEnv(), allow_all=True, allowlist=["10.1.1.1"])
    assert route(lines, "example.com") == "direct"
    assert route(lines, "10.1.1.1") == "direct"
    assert route(lines, "10.1.1.2") == NULL


def test_upstream_host_is_not_allowlisted() -> None:
    lines = upstream_lines(CORP, allow_all=True)
    assert not any("proxy.dev.example" in line and '"' in line for line in lines)


def test_render_config() -> None:
    text = proxy.render_config(
        "Timeout 600\n",
        subnet="172.18.0.0/16",
        filter_path="/var/lib/asb/base.filter",
        upstream=['Upstream none "a"'],
    )
    lines = text.splitlines()
    assert lines[0] == "Timeout 600"
    for expected in (
        "Port 8888",
        "Allow 172.18.0.0/16",
        "LogLevel Connect",
        "FilterDefaultDeny Yes",
        'Filter "/var/lib/asb/base.filter"',
        'Upstream none "a"',
    ):
        assert expected in lines
    assert lines[-1] == proxy.CONFIG_END
    assert not any(line.startswith(("LogFile", "PidFile")) for line in lines)
    open_text = proxy.render_config("", subnet=None, filter_path=None, upstream=[])
    assert "Filter" not in open_text and "Allow" not in open_text


